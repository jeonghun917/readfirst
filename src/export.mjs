// readfirst export --cursor: the map as Cursor project rules, one .cursor/rules/readfirst-<group>.mdc per group, scoped
// to the group's files by glob, so Cursor attaches a group's rules, risks and checks when one of its files is in play.
// The map stays the one source: the files say so at the top, `export --cursor --check` fails when they no longer match
// the map (run it in CI), and export rewrites them. Only files named readfirst-*.mdc are written or removed; any other
// rule in .cursor/rules is the team's own and is left alone.
import { matcher } from './map.mjs';

export const CURSOR_DIR = '.cursor/rules';
export const cursorPath = (id) => `${CURSOR_DIR}/readfirst-${id}.mdc`;
export const isCursorExport = (path) => /^\.cursor\/rules\/readfirst-[a-z0-9-]+\.mdc$/u.test(path);

const oneLine = (s) => String(s).replace(/\s+/gu, ' ').trim();

// { path: text } for every group that has something to say (rules, risks, checks or a replacement).
export function cursorRules(map, files) {
  const out = {};
  for (const g of map.groups) {
    const inGroup = files.filter(matcher(g.files));
    const rules = (map.rules ?? []).filter((r) => inGroup.some(matcher(r.files)));
    // Risks of other groups whose files name a file of this group show in this group's rules too (risksNaming).
    const risks = [...(g.risks ?? []), ...map.groups.filter((o) => o.id !== g.id).flatMap((o) => (o.risks ?? []).filter((r) => Array.isArray(r.files) && r.files.length && inGroup.some(matcher(r.files))))];
    const checks = [...new Map([...(g.checks ?? []), ...rules.flatMap((r) => r.checks ?? [])].map((c) => [c.run, c])).values()];
    if (!rules.length && !risks.length && !checks.length && !g.deprecated) continue;
    const lines = [
      '---',
      `description: ${oneLine(g.title)}`,
      `globs: ${g.files.join(',')}`,
      'alwaysApply: false',
      '---',
      `<!-- Generated by \`readfirst export --cursor\` from .readfirst/map.json (group ${g.id}). Edit the map, not this file. -->`,
      '',
      `# ${oneLine(g.title)}`,
      '',
    ];
    if (g.deprecated) lines.push(`**Being replaced**${g.deprecated.use ? `: use \`${g.deprecated.use}\` instead` : ''}. ${oneLine(g.deprecated.why)} Do not add to it.`, '');
    if (rules.length) lines.push('## Rules that must keep holding', '', ...rules.map((r) => `- **${r.id}**: ${oneLine(r.rule)}${r.why ? ` (why: ${oneLine(r.why)})` : ''}`), '');
    if (risks.length) lines.push('## Watch out', '', ...risks.map((r) => `- ${oneLine(r.text)}${r.files ? ` (${r.files.join(', ')})` : ''}`), '');
    if (checks.length) lines.push('## Run after changing these files', '', ...checks.map((c) => `- \`${c.run}\`${c.why ? `: ${oneLine(c.why)}` : ''}`), '');
    lines.push('For the tests and callers that reach a file, run `npx readfirst read <file>`.', '');
    out[cursorPath(g.id)] = lines.join('\n');
  }
  return out;
}

// What export would change: files to write (new or different) and our files to remove (their group is gone or has
// nothing left to say). read(path) gives the file's current text or null; existing lists the files on disk.
export function cursorPlan(map, files, read, existing) {
  const want = cursorRules(map, files);
  const write = Object.keys(want).filter((p) => read(p) !== want[p]).sort();
  const remove = existing.filter((p) => isCursorExport(p) && !(p in want)).sort();
  return { want, write, remove };
}
