// `readfirst setup --git` (owner's plan A, 2026-11-09): a line in the pre-commit and pre-push hooks, so every agent that
// commits goes through `check` and `verify`, not only the ones that read their notes or use a skill. Added, never
// replacing a hook; left alone and printed when the line would not run or the hook is not this repository's.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { main } from '../src/cli.mjs';
import { MAP_FORMAT } from '../src/map.mjs';

const MAP = JSON.stringify({ format: MAP_FORMAT, groups: [{ id: 'all', title: 'All', files: ['**'] }] });
function repo({ map = true } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'readfirst-setup-git-'));
  const git = (...a) => execFileSync('git', ['-C', root, '-c', 'user.email=t@t', '-c', 'user.name=t', ...a], { encoding: 'utf8' });
  git('init', '-q', '-b', 'main');
  writeFileSync(join(root, 'a.txt'), 'a\n');
  if (map) { mkdirSync(join(root, '.readfirst')); writeFileSync(join(root, '.readfirst/map.json'), MAP); }
  git('add', '.');
  git('commit', '-q', '-m', 'init');
  return { root, git };
}
const run = (root, ...argv) => {
  let out = '';
  const code = main(['--root', root, ...argv], { out: (s) => { out += s; }, err: () => {} });
  return { code, out };
};
const executable = (f) => (statSync(f).mode & 0o111) !== 0;

test('setup --git writes both hooks where git calls them, executable, and a second run adds nothing', () => {
  const { root } = repo();
  const r = run(root, 'setup', '--git');
  assert.equal(r.code, 0);
  for (const [hook, cmd] of [['pre-commit', 'readfirst check'], ['pre-push', 'readfirst verify']]) {
    const f = join(root, '.git/hooks', hook);
    const text = readFileSync(f, 'utf8');
    assert.match(text, /^#!\/bin\/sh\n/u);
    assert.ok(text.includes(`npx --yes ${cmd} || exit 1`), hook);
    assert.ok(executable(f), `${hook} is executable`);
    execFileSync('sh', ['-n', f]); // valid shell
  }
  assert.match(r.out, /wrote: \.git\/hooks\/pre-commit, \.git\/hooks\/pre-push\./u);
  assert.match(r.out, /--no-verify` skips them once/u);
  const again = run(root, 'setup', '--git');
  assert.match(again.out, /already there: \.git\/hooks\/pre-commit, \.git\/hooks\/pre-push\./u);
  assert.equal(readFileSync(join(root, '.git/hooks/pre-commit'), 'utf8').match(/readfirst check/gu).length, 1, 'not added twice');
  assert.ok(!existsSync(join(root, 'AGENTS.md')), '--git writes only the hooks');
});

test('a hook that is there keeps what it had and gets the line at the end', () => {
  const { root } = repo();
  writeFileSync(join(root, '.git/hooks/pre-commit'), '#!/bin/bash\nnpm run lint\n');
  run(root, 'setup', '--git');
  const text = readFileSync(join(root, '.git/hooks/pre-commit'), 'utf8');
  assert.match(text, /^#!\/bin\/bash\nnpm run lint\nnpx --yes readfirst check \|\| exit 1/u);
  assert.ok(executable(join(root, '.git/hooks/pre-commit')), 'made executable: git skips a hook that is not');
});

test('a hook the line would not run in, or that is not a shell script, is left alone and the line printed', () => {
  const { root } = repo();
  const framework = '#!/usr/bin/env bash\n# File generated by pre-commit\nexec pre-commit hook-impl --hook-type=pre-commit "$@"\n';
  writeFileSync(join(root, '.git/hooks/pre-commit'), framework);
  writeFileSync(join(root, '.git/hooks/pre-push'), '#!/usr/bin/env node\nconsole.log(1)\n');
  const r = run(root, 'setup', '--git');
  assert.equal(readFileSync(join(root, '.git/hooks/pre-commit'), 'utf8'), framework, 'unchanged');
  assert.match(r.out, /by hand: \.git\/hooks\/pre-commit hands over with exec, so a line added at the end would never run; add this line to it by hand: npx --yes readfirst check/u);
  assert.match(r.out, /by hand: \.git\/hooks\/pre-push is not a shell script \(#!\/usr\/bin\/env node\)/u);
  assert.doesNotMatch(r.out, /wrote:/u);
});

test('core.hooksPath inside the repository and husky: the hooks go where git and husky run them', () => {
  const a = repo();
  a.git('config', 'core.hooksPath', '.githooks');
  run(a.root, 'setup', '--git');
  assert.match(readFileSync(join(a.root, '.githooks/pre-commit'), 'utf8'), /readfirst check/u);
  assert.ok(!existsSync(join(a.root, '.git/hooks/pre-commit')));
  const b = repo();
  mkdirSync(join(b.root, '.husky/_'), { recursive: true });
  writeFileSync(join(b.root, '.husky/pre-commit'), 'npm test\n');
  b.git('config', 'core.hooksPath', '.husky/_');
  const r = run(b.root, 'setup', '--git');
  assert.equal(readFileSync(join(b.root, '.husky/pre-commit'), 'utf8'), 'npm test\nnpx --yes readfirst check || exit 1 # readfirst: the map places every file (git commit --no-verify skips it once)\n');
  assert.ok(!existsSync(join(b.root, '.husky/_/pre-commit')), "husky's own folder is husky's");
  assert.match(r.out, /git hooks \(\.husky\)/u);
});

test('a hooks folder outside the repository (a global core.hooksPath) and a hook file that leads out are not written', () => {
  const { root, git } = repo();
  const shared = mkdtempSync(join(tmpdir(), 'readfirst-global-hooks-'));
  git('config', 'core.hooksPath', shared);
  const r = run(root, 'setup', '--git');
  assert.ok(!existsSync(join(shared, 'pre-commit')));
  assert.match(r.out, /by hand: .*pre-commit is in a hooks folder outside this repository and its git folder \(.*\), shared with other repositories; add this line to it by hand: npx --yes readfirst check/u);
  const b = repo();
  const elsewhere = join(mkdtempSync(join(tmpdir(), 'readfirst-dotfiles-')), 'pre-commit');
  writeFileSync(elsewhere, '#!/bin/sh\necho shared\n');
  symlinkSync(elsewhere, join(b.root, '.git/hooks/pre-commit'));
  const s = run(b.root, 'setup', '--git');
  assert.equal(readFileSync(elsewhere, 'utf8'), '#!/bin/sh\necho shared\n', 'the shared file is unchanged');
  assert.match(s.out, /by hand: \.git\/hooks\/pre-commit leads outside this repository and its git folder \(to .*readfirst-dotfiles-.*\/pre-commit\); add this line to it by hand/u);
  assert.match(readFileSync(join(b.root, '.git/hooks/pre-push'), 'utf8'), /readfirst verify/u, 'the other hook is still written');
  // The hooks folder itself a link out (a dotfiles folder of hooks shared by every repository).
  const c = repo();
  const dotfiles = mkdtempSync(join(tmpdir(), 'readfirst-dotfiles-hooks-'));
  rmSync(join(c.root, '.git/hooks'), { recursive: true, force: true });
  symlinkSync(dotfiles, join(c.root, '.git/hooks'));
  const t = run(c.root, 'setup', '--git');
  assert.ok(!existsSync(join(dotfiles, 'pre-commit')) && !existsSync(join(dotfiles, 'pre-push')), 'nothing written through the link');
  assert.match(t.out, /by hand: \.git\/hooks\/pre-commit is in a hooks folder outside this repository and its git folder/u);
});

test('a worktree writes the hooks of the repository it belongs to; no map stops before writing', () => {
  const { root, git } = repo();
  const wt = join(mkdtempSync(join(tmpdir(), 'readfirst-wt-')), 'wt');
  git('worktree', 'add', '-q', wt);
  const r = run(wt, 'setup', '--git');
  assert.equal(r.code, 0);
  assert.match(readFileSync(join(root, '.git/hooks/pre-commit'), 'utf8'), /readfirst check/u);
  const none = repo({ map: false });
  assert.throws(() => run(none.root, 'setup', '--git'), /no \.readfirst\/map\.json here: the hooks would fail every commit; `readfirst init` writes a first map/u);
  assert.ok(!existsSync(join(none.root, '.git/hooks/pre-commit')));
});
